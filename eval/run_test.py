"""Phase 4 test stage — the ONE-TIME unlock of the 2025 and 2026 seasons (Gate G4).

Run only after leakage-cop passes and the validation-stage models are final. Steps:
  1. Record the unlock in ``data/test_lock/UNLOCK.json`` (UTC time, git HEAD, sha256 of the frozen model file
     ``data/models/hybrid_v1.pkl``). Re-running later is allowed only if that hash is unchanged, so tables can be
     regenerated byte-for-byte, but no model can be changed after seeing test results.
  2. AFAI grid + feature store for 2025–2026 into ``data/test_lock/`` (never mixed into the train/val store).
  3. P1 arrivals for 2025–2026 with the Phase 3 configuration (``data/test_lock/p1``).
  4. Score every model per season (2025, 2026) and pooled: ``outputs/results_test.csv`` (+ paired, reliability,
     figures). Every baseline and model is fitted only on 2020–2023 (M2's calibration and P1's mapping as in
     the validation stage).
"""

from __future__ import annotations

import hashlib
import json
import pickle
import subprocess
from datetime import UTC, datetime
from pathlib import Path

import numpy as np
import pandas as pd

from eval.metrics import reliability
from eval.run_val import FEATURES, TRAIN_DEFAULT, evaluate

TEST_SEASONS = [2025, 2026]
LOCK = Path("data/test_lock")
UNLOCK = LOCK / "UNLOCK.json"
MODEL_FILE = Path("data/models/hybrid_v1.pkl")
OUT = Path("outputs")
P1_META = OUT / "results_val_p1_meta.json"


def _sha(p: Path) -> str:
    return hashlib.sha256(p.read_bytes()).hexdigest()


def unlock() -> dict:
    sha = _sha(MODEL_FILE)
    if UNLOCK.exists():
        rec = json.loads(UNLOCK.read_text())
        if rec["model_sha256"] != sha:
            raise SystemExit("test already unlocked with a different model file — models are frozen after G4")
        return rec
    head = subprocess.run(["git", "rev-parse", "HEAD"], capture_output=True, text=True).stdout.strip()
    rec = {
        "unlocked_utc": datetime.now(UTC).strftime("%Y-%m-%dT%H:%M:%SZ"),
        "git_head": head,
        "model_sha256": sha,
        "test_seasons": TEST_SEASONS,
    }
    LOCK.mkdir(parents=True, exist_ok=True)
    UNLOCK.write_text(json.dumps(rec, indent=1) + "\n")
    return rec


def build_test_features() -> pd.DataFrame:
    from pipeline.features import afai_grid
    from pipeline.features.build import build

    afai_dir = LOCK / "afai"
    for key in ("1D", "3D"):
        if not (afai_dir / f"stats_{key}.parquet").exists():
            afai_grid.process(key, TEST_SEASONS, out=afai_dir)
    path = LOCK / "features" / "v1" / "features.parquet"
    if path.exists():
        return pd.read_parquet(path)
    df = build(TEST_SEASONS, allow_test=True, afai_dir=afai_dir)
    path.parent.mkdir(parents=True, exist_ok=True)
    df.to_parquet(path, index=False)
    return df


def p1_test(meta: dict) -> pd.DataFrame:
    from physics.drift import run_season

    out = LOCK / "p1"
    for s in TEST_SEASONS:
        run_season(s, (meta["chosen_mode"],), (meta["chosen_windage"],), out=out, zarr=LOCK / "afai" / "3D.zarr")
    from physics.score import load_arrivals

    return load_arrivals(root=out, modes=(meta["chosen_mode"],))


def main() -> None:
    from eval.run_hybrid import attach_p1
    from models.hybrid import stacked_baselines
    from physics.score import fit_mapping, load_arrivals, predict_mapping

    rec = unlock()
    print("test unlocked:", rec)
    p1meta = json.loads(P1_META.read_text())
    test = build_test_features()
    arr = p1_test(p1meta)
    arr = arr[np.isclose(arr.windage, p1meta["chosen_windage"])]
    p1cols = arr[["site", "date", "lead", "idx_window", "idx_cum"]].rename(
        columns={"idx_window": "p1_idx_window", "idx_cum": "p1_idx_cum"}
    )
    raw_idx = p1cols[["site", "date", "lead", "p1_idx_window"]].rename(columns={"p1_idx_window": "idx_window"})
    p1cols[["p1_idx_window", "p1_idx_cum"]] = np.log1p(p1cols[["p1_idx_window", "p1_idx_cum"]])
    test = test.merge(p1cols, on=["site", "date", "lead"], how="left")

    feats, _ = attach_p1(pd.read_parquet(FEATURES))
    tr = feats[feats.season.isin(TRAIN_DEFAULT)].reset_index(drop=True)
    _, (te,) = stacked_baselines(tr, [test])
    with MODEL_FILE.open("rb") as f:
        bundle = pickle.load(f)
    models = bundle["models"]

    preds = pd.DataFrame(index=te.index)
    from models.baselines import fit_all, predict_all

    base = predict_all(fit_all(tr), te)
    for k in ("B0", "B1", "B2", "B3", "B3_fc"):
        preds[k] = base[k]
    # P1 alone: same mapping as the validation stage (fit on the training seasons of the chosen configuration)
    arr_tr = load_arrivals(modes=(p1meta["chosen_mode"],))
    arr_tr = arr_tr[np.isclose(arr_tr.windage, p1meta["chosen_windage"])]
    lab = feats[["site", "date", "lead", "season", "event"]]
    trp = lab.merge(arr_tr[["site", "date", "lead", "idx_window"]], on=["site", "date", "lead"])
    mapping = fit_mapping(trp[trp.season.isin(p1meta["mapping_train_seasons"])])
    te_idx = te[["site", "date", "lead"]].merge(raw_idx, on=["site", "date", "lead"], how="left")
    n_missing = int(te_idx["idx_window"].isna().sum())
    if n_missing:  # empty-seed days write explicit zero tables, so a gap means a failed run: never fill silently
        raise SystemExit(f"{n_missing} test rows have no P1 arrival record — rerun the missing issue days")
    preds["P1"] = predict_mapping(mapping, te_idx)
    for abl, h in models.items():
        name = "M1" if abl == "full" else f"M1_{abl}"
        preds[name] = h.predict_m1(te)
        if abl == "full":
            preds["M2"] = h.predict_m2(te)
        if abl == "fc":
            preds["M2_fc"] = h.predict_m2(te)
    names = list(preds.columns)

    frames, pframes, rels = [], [], []
    for label, mask in [("2025", te.season == 2025), ("2026", te.season == 2026), ("2025-2026", te.season > 0)]:
        sub, ps = te[mask].reset_index(drop=True), preds[mask].reset_index(drop=True)
        r, p = evaluate(sub, ps, names)
        frames.append(r.assign(season=label))
        pframes.append(p.assign(season=label))
        for k in names:
            for lead in [1, 2, 3, 5, 7, "all"]:
                m = np.ones(len(sub), bool) if lead == "all" else (sub["lead"] == lead).to_numpy()
                rels.append(
                    reliability(sub["event"].to_numpy()[m], ps[k].to_numpy()[m]).assign(
                        model=k, lead=str(lead), season=label
                    )
                )
    res, paired, rel = pd.concat(frames), pd.concat(pframes), pd.concat(rels)
    res.to_csv(OUT / "results_test.csv", index=False, float_format="%.4f")
    paired.to_csv(OUT / "results_test_paired.csv", index=False, float_format="%.4f")
    rel.to_csv(OUT / "reliability_test.csv", index=False, float_format="%.4f")
    keep = ["site", "date", "lead", "season", "event", "last_event", "event_rate_7d"]
    pd.concat([te[keep], preds], axis=1).to_parquet(LOCK / "preds_test.parquet")
    (OUT / "results_test_meta.json").write_text(
        json.dumps({**rec, "models": names, "p1": p1meta, "train_seasons": TRAIN_DEFAULT}, indent=1) + "\n"
    )
    from eval.figures import test_figures

    test_figures(res, rel, OUT / "figures")
    show = res[(res.lead == "all")][
        [
            "season",
            "model",
            "brier",
            "bss_B0",
            "bss_B0_lo",
            "bss_B0_hi",
            "bss_B1",
            "bss_B1_lo",
            "bss_B1_hi",
            "auc",
            "auc_lo",
            "auc_hi",
        ]
    ]
    print(show.to_string(index=False, float_format=lambda v: f"{v:.3f}"))


if __name__ == "__main__":
    main()
